import type { RadiusStop } from "@/core/tokens";
import type { UiStyleSpec } from "./types";

function formatPaletteBlock(label: string, p: UiStyleSpec["dark"]): string {
  return [
    `### ${label}`,
    `- **Canvas**: \`${p.canvas}\``,
    `- **Surface**: \`${p.surface}\``,
    `- **Elevated**: \`${p.elevated}\``,
    `- **Border**: \`${p.border}\``,
    `- **Primary Ink**: \`${p.ink}\``,
    `- **Muted Ink**: \`${p.muted}\``,
    `- **Accent**: \`${p.accent}\` (Foreground \`${p.accentFg}\`)`
  ].join("\n");
}

export function compileStyleDesignMd(style: UiStyleSpec): string {
  const scenariosYaml = style.scenarios.map((s) => `"${s}"`).join(", ");
  const dosBlock = style.dosEn.map((rule) => `- **DO**: ${rule}`).join("\n");
  const dontsBlock = style.dontsEn.map((rule) => `- **DON'T**: ${rule}`).join("\n");

  return `---
protocol: "DESIGN.md"
version: "1.0"
kind: "ui-style"
slug: "${style.slug}"
name: "${style.name}"
name_zh: "${style.nameZh}"
group: "${style.group}"
primary_tone: "${style.primaryTone}"
default_radius: "${style.defaultRadius}px"
surface_effect: "${style.surfaceEffect}"
scenarios: [${scenariosYaml}]
---

# ${style.name} (${style.nameZh}) — UI Style Protocol

${style.summaryEn}

## 1. Visual Physics & Surface Signature
- **Default Radius**: \`${style.defaultRadius}px\` (${style.radiusLabelEn})
- **Border Contract**: \`${style.borderSpec}\`
- **Elevation & Shadow**: \`${style.shadowSpec}\`
- **Surface Material**: \`${style.surfaceEffect}\`

## 2. Dual-Mode Color Tokens

${formatPaletteBlock("Dark Mode Tokens", style.dark)}

${formatPaletteBlock("Light Mode Tokens", style.light)}

## 3. Typography Pairing
- **Display Font**: ${style.fonts.display} (tracking \`${style.fonts.tracking}\`)
- **Body Font**: ${style.fonts.body}
- **Monospace / Metrics**: ${style.fonts.mono} (\`font-variant-numeric: tabular-nums\`)

## 4. Implementation Guardrails
${dosBlock}
${dontsBlock}
`;
}

/**
 * Generates copy-ready CSS variables (:root + .dark + Tailwind v4 @theme inline)
 * for a UI style, reacting dynamically to live radius stop adjustments.
 */
export function compileStyleCssVariables(
  style: UiStyleSpec,
  radiusOverride?: RadiusStop
): string {
  const radius = radiusOverride ?? style.defaultRadius;
  const ctrlRadius = radius === 0 ? 0 : Math.max(4, Math.round(radius * 0.65));

  return `/* UI Style: ${style.name} (${style.nameZh}) — Generated by UIFino */
:root {
  --ui-canvas: ${style.light.canvas};
  --ui-surface: ${style.light.surface};
  --ui-elevated: ${style.light.elevated};
  --ui-border: ${style.light.border};
  --ui-ink: ${style.light.ink};
  --ui-muted: ${style.light.muted};
  --ui-accent: ${style.light.accent};
  --ui-accent-fg: ${style.light.accentFg};
  --ui-radius-card: ${radius}px;
  --ui-radius-ctrl: ${ctrlRadius}px;
  --ui-tracking-display: ${style.fonts.tracking};
}

.dark,
html[data-theme="dark"] {
  --ui-canvas: ${style.dark.canvas};
  --ui-surface: ${style.dark.surface};
  --ui-elevated: ${style.dark.elevated};
  --ui-border: ${style.dark.border};
  --ui-ink: ${style.dark.ink};
  --ui-muted: ${style.dark.muted};
  --ui-accent: ${style.dark.accent};
  --ui-accent-fg: ${style.dark.accentFg};
}

@theme inline {
  --color-canvas: var(--ui-canvas);
  --color-surface: var(--ui-surface);
  --color-elevated: var(--ui-elevated);
  --color-border: var(--ui-border);
  --color-ink: var(--ui-ink);
  --color-muted: var(--ui-muted);
  --color-accent: var(--ui-accent);
  --color-accent-fg: var(--ui-accent-fg);
  --radius-card: var(--ui-radius-card);
  --radius-ctrl: var(--ui-radius-ctrl);
}
`;
}
