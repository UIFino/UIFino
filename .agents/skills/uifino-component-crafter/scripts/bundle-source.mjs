#!/usr/bin/env node
/**
 * UIFino Verbatim Component Source Bundler
 *
 * Reads `component.tsx` and `demo.tsx` inside `src/registry/components/<relPath>/`
 * and writes `source.ts` exporting `filesSource` with exact PascalCase filenames.
 *
 * Usage:
 *   node .agents/skills/uifino-component-crafter/scripts/bundle-source.mjs sections/hero/hero-telemetry-counter
 */

import fs from "node:fs";
import path from "node:path";

const relPath = process.argv[2];
if (!relPath) {
  console.error("Usage: node bundle-source.mjs <sections|blocks|motion>/<category>/<slug>");
  process.exit(1);
}

const compDir = path.resolve("src", "registry", "components", relPath);
const slug = path.basename(compDir);
const pascal = slug
  .split("-")
  .filter(Boolean)
  .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
  .join("");

const compFile = path.join(compDir, "component.tsx");
const demoFile = path.join(compDir, "demo.tsx");

if (!fs.existsSync(compFile) || !fs.existsSync(demoFile)) {
  console.error(`[FAIL] Both component.tsx and demo.tsx must exist in ${compDir}`);
  process.exit(1);
}

const compCode = fs.readFileSync(compFile, "utf8").replace(/\r\n/g, "\n").trim() + "\n";
const demoRaw = fs.readFileSync(demoFile, "utf8").replace(/\r\n/g, "\n").trim() + "\n";
// Rewrite relative `./component` import to `./<PascalName>` for clean user copy-paste
const demoClean = demoRaw.replace(/from\s+["']\.\/component["']/g, `from "./${pascal}"`);

const out = `// Auto-generated by bundle-source.mjs — do not edit manually
export const filesSource: Readonly<Record<string, string>> = {
  ${JSON.stringify(`${pascal}.tsx`)}: ${JSON.stringify(compCode)},
  ${JSON.stringify(`${pascal}Demo.tsx`)}: ${JSON.stringify(demoClean)}
};
`;

const target = path.join(compDir, "source.ts");
fs.writeFileSync(target, out, "utf8");
console.log(`[bundle] Generated ${target} (${pascal}.tsx + ${pascal}Demo.tsx)`);
